for x in NEW:
    if any(y["n"] == x["n"] for y in d):
        print("! 已存在，跳过:", x["n"]); continue
    d.append(x); added += 1

for key, note in EXTRA:
    for x in d:
        if key in x["n"]:
            if note not in (x.get("rm") or ""):
                x["rm"] = ((x.get("rm") or "") + " ｜ " + note).strip(" ｜")
            break

