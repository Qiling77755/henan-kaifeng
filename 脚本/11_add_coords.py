n_exact = n_approx = 0
for i, (la, ln, src) in DIRECT.items():
    x = by_id.get(i)
    if not x:
        print("!! 无此 id", i); continue
    x["lat"], x["lng"], x["loc"] = la, ln, "exact"
    if src not in (x.get("rm") or ""):
        x["rm"] = ((x.get("rm") or "").strip() + " ｜ " + src).strip(" ｜")
    n_exact += 1

for key, ids in APPROX.items():
    la0, ln0, label = ANCHORS[key]
    for i in ids:
        x = by_id.get(i)
        if not x or x.get("lat"):
            continue
        # 确定性微偏移（约 ±100m），避免完全重叠
        dy = ((i * 37) % 100 / 100 - 0.5) * 0.0018
        dx = ((i * 53) % 100 / 100 - 0.5) * 0.0022
        x["lat"] = round(la0 + dy, 6)
        x["lng"] = round(ln0 + dx, 6)
        x["loc"] = "approx"
        x["ad"] = (x.get("ad") or "") or ("%s 一带（无独立 POI）" % label)
        n_approx += 1

